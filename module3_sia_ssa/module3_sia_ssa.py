"""
Модуль 3: Численное моделирование течения льда (SIA и SSA)
=============================================================

Курс по гляциологии — практическая реализация на Python.

Содержание:
1. Приближение мелкого льда (SIA) — диффузионная модель эволюции толщины
2. Приближение мелкого шельфа (SSA) — мембранная (продольная) модель течения
3. Сравнение профилей скорости по глубине: SIA (сдвиг) vs SSA (пробковое течение)
4. Решение уравнения непрерывности dH/dt = -dq/dx + b(x) во времени

Требуемые библиотеки: numpy, matplotlib, scipy
Установка: pip install numpy matplotlib scipy
"""

import numpy as np
import matplotlib.pyplot as plt

# =============================================================================
# ФИЗИЧЕСКИЕ КОНСТАНТЫ И ПАРАМЕТРЫ ЗАКОНА ГЛЕНА
# =============================================================================

RHO_ICE = 917.0     # плотность льда, кг/м^3
RHO_WATER = 1028.0  # плотность морской воды, кг/м^3
G = 9.81            # ускорение свободного падения, м/с^2
N_GLEN = 3.0         # показатель степени закона Глена
A_SOFTNESS = 2.4e-24  # коэффициент мягкости, Па^-3 с^-1 (типично для T ~ -10°C)


# =============================================================================
# 1. ПРИБЛИЖЕНИЕ МЕЛКОГО ЛЬДА (SIA)
# =============================================================================
#
# В приближении SIA продольные (мембранные) напряжения пренебрежимо малы
# по сравнению с вертикальным сдвигом. Диффузионный поток льда:
#
#   q = -D * dS/dx,   где S = B + H (высота поверхности)
#
#   D = (2A / (n+2)) * (rho*g)^n * H^(n+2) * |dS/dx|^(n-1)
#
# Уравнение неразрывности:  dH/dt = -dq/dx + b(x,t)
# где b(x,t) — баланс массы (аккумуляция/абляция), м/год (в виде толщины льда)


def sia_diffusivity(H, dS_dx, A=A_SOFTNESS, n=N_GLEN):
    """
    Диффузионный коэффициент SIA.

    Параметры
    ----------
    H : np.ndarray
        Толщина льда, м
    dS_dx : np.ndarray
        Уклон поверхности (dS/dx), безразмерный
    """
    return (2 * A / (n + 2)) * (RHO_ICE * G) ** n * H ** (n + 2) * np.abs(dS_dx) ** (n - 1)


def sia_surface_velocity(H, dS_dx, A=A_SOFTNESS, n=N_GLEN):
    """
    Поверхностная скорость деформации (без учёта скольжения по ложу) по SIA.

        u_def(surf) = (2A / (n+1)) * (rho*g)^n * H^(n+1) * |dS/dx|^(n-1) * dS/dx
    """
    return -(2 * A / (n + 1)) * (RHO_ICE * G) ** n * H ** (n + 1) * np.abs(dS_dx) ** (n - 1) * dS_dx


def sia_velocity_profile(z, H, dS_dx, A=A_SOFTNESS, n=N_GLEN, u_basal=0.0):
    """
    Профиль горизонтальной скорости по глубине для SIA (без скольжения
    либо с заданной базальной скоростью u_basal).

    Скорость нарастает от ложа (z=0) к поверхности (z=H) за счёт
    накопления сдвиговой деформации:

        u(z) = u_basal + (2A/(n+1)) * (rho*g*|dS/dx|)^n * (H^(n+1) - (H-z)^(n+1))

    Параметры
    ----------
    z : np.ndarray
        Высота над ложем, м (0 <= z <= H)
    H, dS_dx : float
        Толщина льда и уклон поверхности в данной точке
    """
    coef = (2 * A / (n + 1)) * (RHO_ICE * G * np.abs(dS_dx)) ** n
    return u_basal + coef * (H ** (n + 1) - np.clip(H - z, 0, None) ** (n + 1))


# -----------------------------------------------------------------------
# ВАЖНОЕ ЗАМЕЧАНИЕ О РЕАЛИСТИЧНОСТИ СКОРОСТЕЙ
# -----------------------------------------------------------------------
# Чистая SIA-деформация (закон Глена без скольжения) систематически
# ЗАНИЖАЕТ реальные скорости большинства ледников. По данным ITS_LIVE
# (NASA MEaSUREs, https://its-live.jpl.nasa.gov/) и литературы:
#   - внутренняя часть ледниковых щитов (только деформация):  ~1-20 м/год
#   - типичные горные/выводные ледники:                       10-500 м/год
#     (AntarcticGlaciers.org, "Measuring glacier velocity")
#   - быстрые выводные ледники (Jakobshavn, Pine Island):  3900-15000 м/год
#     (Joughin et al. 2004; Lemos et al. 2018)
#
# Для большинства выводных ледников бОльшая часть наблюдаемой скорости —
# это именно БАЗАЛЬНОЕ СКОЛЬЖЕНИЕ, а не внутренняя деформация льда.
# Полная физика скольжения (в т.ч. зависимость от эффективного давления
# и кавитации) разбирается в Модуле 4 (закон Зоэта-Иверсона). Здесь для
# реалистичности добавлена упрощённая параметризация скольжения по
# Веертману (Weertman, 1957): u_b = C_slide * tau_b^p


C_SLIDE_DEFAULT = 3.2e-21  # эмпирический коэффициент скольжения, м с^-1 Па^-p
P_SLIDE_DEFAULT = 3.0       # показатель степени закона скольжения


def weertman_sliding_velocity(H, dS_dx, C_slide=C_SLIDE_DEFAULT, p=P_SLIDE_DEFAULT):
    """
    Упрощённая скорость базального скольжения по закону Веертмана:

        u_b = C_slide * tau_b^p,   tau_b = rho_ice * g * H * |dS/dx|

    Это грубое приближение без учёта эффективного давления на ложе;
    полная модель — в Модуле 4 (universal sliding law Zoet & Iverson).
    Коэффициент C_slide откалиброван так, чтобы при typичных значениях
    базального напряжения (~100-150 кПа) скорость скольжения была
    порядка первых сотен м/год — соответствует наблюдениям ITS_LIVE для
    умеренно быстрых выводных ледников.
    """
    tau_b = RHO_ICE * G * H * np.abs(dS_dx)
    u_b_magnitude = C_slide * tau_b ** p
    return -np.sign(dS_dx) * u_b_magnitude  # то же направление, что и деформация


def sia_surface_velocity_total(H, dS_dx, A=A_SOFTNESS, n=N_GLEN,
                                 include_sliding=True, C_slide=C_SLIDE_DEFAULT, p=P_SLIDE_DEFAULT):
    """
    Полная поверхностная скорость = деформация (Глен) + скольжение (Веертман).
    """
    u_def = sia_surface_velocity(H, dS_dx, A, n)
    if not include_sliding:
        return u_def
    u_slide = weertman_sliding_velocity(H, dS_dx, C_slide, p)
    return u_def + u_slide


def run_sia_flowline(
    x, bed, H0, mass_balance_func,
    A=A_SOFTNESS, n=N_GLEN,
    dt_years=1.0, n_years=200,
):
    """
    Полу-неявная (backward Euler) конечно-разностная схема для эволюции
    толщины ледника в приближении SIA.

    Уравнение dH/dt = d/dx(D dS/dx) + b нелинейно из-за зависимости D(H),
    поэтому используется линеаризация "с запаздыванием" (lagged diffusivity):
    на каждом шаге коэффициент D вычисляется по текущему известному H,
    а полученная линейная система решается неявно (безусловно устойчиво
    относительно шага по времени dt — в отличие от явной схемы, которая
    для степенной диффузии SIA (D ~ H^(n+2)) требует крайне малых dt).

    Параметры
    ----------
    x : np.ndarray
        Сетка по горизонтали, м
    bed : np.ndarray
        Высота ложа, м
    H0 : np.ndarray
        Начальная толщина льда, м
    mass_balance_func : callable
        Функция b(x) -> баланс массы, м льда / год
    dt_years : float
        Шаг по времени, годы
    n_years : int
        Число лет моделирования

    Возвращает
    -------
    dict с историей толщины H_history (список массивов) и временными метками
    """
    dx = x[1] - x[0]
    dt = dt_years * 365.25 * 24 * 3600  # секунды
    H = H0.copy()
    b = mass_balance_func(x) / (365.25 * 24 * 3600)  # м/с толщины льда
    N = len(x)

    n_steps = int(n_years / dt_years)
    save_every = max(1, n_steps // 50)
    H_history = [H.copy()]
    t_history = [0.0]

    for step in range(1, n_steps + 1):
        S = bed + H
        dS_dx = np.gradient(S, dx)
        D = sia_diffusivity(H, dS_dx, A, n)

        # Диффузивность на гранях ячеек (среднее между соседними узлами)
        D_face = np.zeros(N + 1)
        D_face[1:-1] = 0.5 * (D[:-1] + D[1:])
        D_face[0] = 0.0   # нулевой поток на левой границе (водораздел)
        D_face[-1] = 0.0  # нулевой поток на правой границе (за пределами языка)

        alpha = D_face * dt / dx ** 2  # безразмерный диффузионный параметр Куранта

        lower = -alpha[:-1]
        upper = -alpha[1:]
        diag = 1.0 + alpha[:-1] + alpha[1:]

        # Система собирается относительно H (bed известен и постоянен на
        # шаге); S = bed + H, поэтому вклад соседних bed переносится в rhs:
        bed_left = np.concatenate(([bed[0]], bed[:-1]))
        bed_right = np.concatenate((bed[1:], [bed[-1]]))

        rhs = H + dt * b + alpha[:-1] * bed_left + alpha[1:] * bed_right \
              - (alpha[:-1] + alpha[1:]) * bed

        H_new = _thomas_solve(lower, diag, upper, rhs)
        H = np.clip(H_new, 0.0, None)

        if step % save_every == 0:
            H_history.append(H.copy())
            t_history.append(step * dt_years)

    return {"x": x, "bed": bed, "H_history": H_history, "t_history": t_history, "H_final": H}


# =============================================================================
# 2. ПРИБЛИЖЕНИЕ МЕЛКОГО ШЕЛЬФА (SSA)
# =============================================================================
#
# Для плавучего шельфового льда вертикальный сдвиг мал, и течение близко
# к "пробковому" (plug flow) — скорость почти не меняется по глубине.
# Полный баланс продольных напряжений (без базального и бокового трения):
#
#   d/dx [ 2 H \bar{eta} du/dx ] = rho_i * g * H * dS/dx
#
# где 2*H*\bar{eta}*du/dx — это "мембранная" (продольная резистивная) сила.
# Интегрируя один раз по x и используя граничное условие на фронте откола
# (баланс гидростатического давления льда и океана), правая и левая части
# совпадают почтенно при ЛЮБОМ x — это классический результат Веертмана
# (Weertman, 1957) для неограниченного берегами шельфа:
#
#   2 H \bar{eta} du/dx = (1/4) * rho_i * g * (1 - rho_i/rho_w) * H^2
#
# Комбинируя это с уравнением неразрывности в стационарном состоянии без
# аккумуляции/абляции (поток массы Q = u*H = const), получаем ОДУ только
# для u(x), которое интегрируется аналитически:
#
#   u(x) = [ u0^(n+1) + (n+1) * (A/2^n) * (rho_i g (1-rho_i/rho_w))^n * Q^n * x ]^(1/(n+1))
#   H(x) = Q / u(x)
#
# Это самосогласованное решение: в отличие от произвольно заданного
# профиля H(x), здесь толщина автоматически удовлетворяет неразрывности,
# что даёт физически корректный (не "разгоняющийся" искусственно) результат.


def solve_ssa_shelf_analytic(x, u0, H0, A=A_SOFTNESS, n=N_GLEN):
    """
    Аналитическое решение Веертмана для неограниченного берегами
    ("unconfined") шельфового ледника: скорость и толщина как функции
    расстояния от линии налегания (x=0).

    Параметры
    ----------
    x : np.ndarray
        Расстояние от линии налегания, м (x[0] = 0)
    u0 : float
        Скорость на линии налегания, м/с
    H0 : float
        Толщина льда на линии налегания, м
    A, n : float
        Параметры закона Глена

    Возвращает
    -------
    u : np.ndarray
        Скорость вдоль шельфа, м/с
    H : np.ndarray
        Толщина льда вдоль шельфа, м (из условия сохранения потока Q=u*H)
    """
    Q = u0 * H0  # поток массы (сохраняется вдоль шельфа при отсутствии таяния/намерзания)
    K = (A / 2.0 ** n) * (RHO_ICE * G * (1 - RHO_ICE / RHO_WATER)) ** n * Q ** n
    u = (u0 ** (n + 1) + (n + 1) * K * x) ** (1.0 / (n + 1))
    H = Q / u
    return u, H


def _thomas_solve(lower, diag, upper, rhs):
    """Метод прогонки (алгоритм Томаса) для трёхдиагональной системы."""
    N = len(diag)
    c_ = np.zeros(N)
    d_ = np.zeros(N)
    c_[0] = upper[0] / diag[0]
    d_[0] = rhs[0] / diag[0]
    for i in range(1, N):
        m = diag[i] - lower[i] * c_[i - 1]
        c_[i] = upper[i] / m if i < N - 1 else 0.0
        d_[i] = (rhs[i] - lower[i] * d_[i - 1]) / m

    x_sol = np.zeros(N)
    x_sol[-1] = d_[-1]
    for i in range(N - 2, -1, -1):
        x_sol[i] = d_[i] - c_[i] * x_sol[i + 1]
    return x_sol


