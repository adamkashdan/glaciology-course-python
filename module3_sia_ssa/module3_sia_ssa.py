# 4. ДЕМОНСТРАЦИЯ: эволюция ледникового профиля (SIA) во времени
# =============================================================================

def demo_sia_evolution():
    """
    Запускает SIA flowline-модель для идеализированного ледника на наклонном
    ложе с параметризованным балансом массы (аккумуляция выше ELA, абляция
    ниже), и строит эволюцию профиля толщины во времени.
    """
    L = 30000.0       # длина домена, м
    nx = 150
    x = np.linspace(0, L, nx)

    bed = 2000.0 - 0.05 * x  # линейно наклонное ложе
    H0 = np.maximum(300.0 * (1 - x / L), 0.0)  # начальный клиновидный профиль

    ELA = 15000.0  # высота линии равновесного баланса по x (упрощённо)
    grad_b = 0.008  # градиент баланса массы, (м/год)/м вдоль x

    def mass_balance(x_arr):
        return np.clip(grad_b * (ELA - x_arr), -5.0, 2.0)

    result = run_sia_flowline(
        x, bed, H0, mass_balance,
        dt_years=0.25, n_years=300,
    )

    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5))
    n_curves = len(result["H_history"])
    colors = plt.cm.viridis(np.linspace(0, 1, n_curves))

    for i, (H, t) in enumerate(zip(result["H_history"], result["t_history"])):
        if i == 0 or i == n_curves - 1 or i % max(1, n_curves // 6) == 0:
            S = result["bed"] + H
            axes[0].plot(x / 1000, S, color=colors[i], lw=1.5,
                     label=f"t = {t:.0f} лет" if (i == 0 or i == n_curves - 1) else None,
                     alpha=0.8)

    axes[0].plot(x / 1000, result["bed"], color="black", lw=2, label="Ложе")
    axes[0].set_xlabel("Расстояние вдоль потока, км")
    axes[0].set_ylabel("Высота, м")
    axes[0].set_title("Эволюция профиля ледника (модель SIA, конечные разности)")
    axes[0].legend(fontsize=9)
    axes[0].grid(alpha=0.3)

    # Скорость поверхности для финального (квазиравновесного) профиля —
    # проверка реалистичности: внутренняя часть ледникового щита по
    # данным ITS_LIVE обычно течёт со скоростью ~1-20 м/год.
    H_final = result["H_final"]
    S_final = bed + H_final
    dS_dx_final = np.gradient(S_final, x)
    u_final = sia_surface_velocity_total(H_final, dS_dx_final) * (365.25 * 24 * 3600)

    # У самого края языка (H -> 0) конечно-разностный градиент поверхности
    # даёт завышенный, физически малодостоверный всплеск скорости —
    # стандартный краевой артефакт SIA-схем. Маскируем точки с H < 10 м.
    valid = H_final > 10.0
    u_plot = np.where(valid, u_final, np.nan)

    axes[1].plot(x / 1000, u_plot, color="#9467bd", lw=2)
    axes[1].axhspan(1, 20, color="gray", alpha=0.15, label="Типичный диапазон ITS_LIVE\nдля внутр. части щита (1-20 м/год)")
    axes[1].set_xlabel("Расстояние вдоль потока, км")
    axes[1].set_ylabel("Поверхностная скорость, м/год")
    axes[1].set_title("Скорость (деформация + скольжение), t = 300 лет")
    axes[1].legend(fontsize=8)
    axes[1].grid(alpha=0.3)

    fig.tight_layout()
