def demo_ssa_shelf():
    """
    Аналитическое (Веертман) решение SSA для идеализированного
    неограниченного шельфового ледника: скорость нарастает, а толщина
    убывает от линии налегания к фронту откола, самосогласованно с
    уравнением неразрывности (Q = u*H = const).
    """
    L_shelf = 50000.0  # длина шельфа, м
    nx = 200
    x = np.linspace(0, L_shelf, nx)

    H0 = 500.0   # толщина на линии налегания, м
    u0 = 300.0 / (365.25 * 24 * 3600)  # скорость на линии налегания, м/с

    u, H = solve_ssa_shelf_analytic(x, u0, H0)
    u_years = u * 365.25 * 24 * 3600

    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    axes[0].plot(x / 1000, H, color="#2ca02c", lw=2)
    axes[0].set_xlabel("Расстояние от линии налегания, км")
    axes[0].set_ylabel("Толщина льда, м")
    axes[0].set_title("Профиль толщины шельфа (из Q = u·H = const)")
    axes[0].grid(alpha=0.3)

    axes[1].plot(x / 1000, u_years, color="#ff7f0e", lw=2)
    axes[1].set_xlabel("Расстояние от линии налегания, км")
    axes[1].set_ylabel("Скорость, м/год")
    axes[1].set_title("Скорость течения шельфа (аналитич. решение SSA)")
    axes[1].grid(alpha=0.3)

    fig.suptitle("Модель мелкого шельфа (SSA): ускорение и утоньшение к фронту откола", fontsize=12)
    fig.tight_layout()
    fig.savefig("/mnt/user-data/outputs/ssa_shelf_velocity.png", dpi=150)
    plt.close(fig)

    return x, H, u_years


